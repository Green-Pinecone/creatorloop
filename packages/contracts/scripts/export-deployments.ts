// Export addresses + ABIs for the web app (TypeScript) and the API (Python).
// Usage: pnpm --filter @creatorloop/contracts export <startBlock> [deploymentId=amoy]
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const startBlock = Number(process.argv[2]);
const id = process.argv[3] ?? "amoy";
if (!Number.isInteger(startBlock) || startBlock < 0) {
  console.error("usage: export <startBlock> [deploymentId]");
  process.exit(1);
}

const root = path.resolve(import.meta.dirname, "..");
const dep = path.join(root, "ignition/deployments", id);
const addrs = JSON.parse(readFileSync(path.join(dep, "deployed_addresses.json"), "utf8"));
const names = ["CreatorPosts", "Tipping", "LoopToken", "RewardDistributor"] as const;
const abi = (n: string) =>
  JSON.parse(readFileSync(path.join(dep, "artifacts", `CreatorLoop#${n}.json`), "utf8")).abi;

const deployment = {
  chainId: id === "amoy" ? 80002 : 31337,
  startBlock,
  deploymentId: id,
  ...Object.fromEntries(names.map((n) => [n, addrs[`CreatorLoop#${n}`]])),
};

// TypeScript consumers
const shared = path.resolve(root, "../shared/src");
mkdirSync(path.join(shared, "deployments"), { recursive: true });
writeFileSync(path.join(shared, "deployments/amoy.json"), JSON.stringify(deployment, null, 2) + "\n");
writeFileSync(
  path.join(shared, "abis.ts"),
  "// Generated by packages/contracts/scripts/export-deployments.ts. Do not edit.\n\n" +
    names
      .map((n) => `export const ${n[0].toLowerCase() + n.slice(1)}Abi = ${JSON.stringify(abi(n))} as const;`)
      .join("\n\n") +
    "\n",
);

// Python consumer
const py = path.resolve(root, "../../services/api/app/chain/abis");
mkdirSync(py, { recursive: true });
for (const n of names) writeFileSync(path.join(py, `${n}.json`), JSON.stringify(abi(n), null, 2) + "\n");
writeFileSync(path.join(py, "deployments.json"), JSON.stringify(deployment, null, 2) + "\n");

console.log(deployment);
